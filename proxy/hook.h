// hook.h -- the entry / mid-function hook engine shared by every fix in this proxy.
//
// A fix describes its patch sites in a HookDef table (stolen bytes recorded from the analysed
// binary with tools/ghidra/dump_prologue.py, checked against the on-disk DLL with
// tools/re/check_prologues.py) and installs them in four steps, so it can do its own work in
// between (logging, allocating its tables, arming its state before the first hit):
//
//   1. Hook_GameModule      find empire.retail.dll (optionally require the analysed SizeOfImage)
//   2. Hook_SiteMatches     byte-check EVERY site before writing any; on a mismatch install nothing
//   3. Hook_Prepare         build the trampolines (stolen bytes as they are in memory + JMP back)
//   4. Hook_Patch           write JMP detour + NOP padding into each prepared site
//
// Hook_Remove restores the original bytes. The detour of a hook is a naked stub that saves the
// registers, passes a pointer to them to a __stdcall handler and jumps through the hook's
// trampoline; HOOK_DETOUR below emits it. The stack offsets a handler reads come from a header
// generated by tools/re/stack_calc.py for exactly that sequence (pushad, pushfd, mark:ctx,
// push:ctxptr). Never calculate them by hand.
//
// Mid-function sites need no special case: the stolen bytes are whole instructions with no
// branch into them (checked by dump_prologue.py), so the trampoline runs them and jumps back.
// An absolute address inside the stolen bytes (relocOff >= 0) is compared after adding the
// module's rebase delta; the copy in the trampoline is the in-memory, already rebased one.
//
// No logging here: the public DLL compiles this file too, without the logger.
#pragma once
#include <windows.h>
#include <cstdint>

static const int HOOK_MAX_STOLEN = 16;
static const uint32_t HOOK_ANALYSED_IMAGE_BASE = 0x10000000;   // s2x86 / Ghidra names
static const uint32_t HOOK_ANALYSED_IMAGE_SIZE = 0x01D88000;   // SizeOfImage of the analysed build

struct HookDef {
    const char* func;       // Ghidra name in s2x86 (or name+offset for a mid-function site)
    const char* role;
    uint32_t    rva;
    int         len;        // stolen bytes, whole instructions, no branch into the range, >= 5
    uint8_t     expected[HOOK_MAX_STOLEN];
    int         relocOff;   // offset of an absolute address inside the stolen bytes, or -1
    bool        probeOnly;  // the fix decides (Hook_Prepare's `use`); the engine ignores it
};

// Per-site install state, one per HookDef, owned by the fix.
struct HookSlot {
    uint8_t* target;                       // null = not prepared
    uint8_t  original[HOOK_MAX_STOLEN];
    int      len;
    bool     active;                       // patched
};

typedef void (*HookDetour)();

// empire.retail.dll in this process, or null. With requireSize, null unless its SizeOfImage is
// HOOK_ANALYSED_IMAGE_SIZE. sizeOut (optional) receives the SizeOfImage either way.
uint8_t* Hook_GameModule(bool requireSize, uint32_t* sizeOut);

// The module's load address minus the analysed image base.
uint32_t Hook_RebaseDelta(const uint8_t* base);

// The bytes expected at a site in this process (relocOff rebased).
void Hook_Expected(const HookDef& d, uint32_t delta, uint8_t* out);

// True when the bytes at base + d.rva are the expected ones.
bool Hook_SiteMatches(const uint8_t* base, const HookDef& d);

// Builds a trampoline for every hook h with use == null or use[h] true: tramps[h] receives it
// (the naked detour jumps through tramps[h]) and slots[h] records the site and its original
// bytes. Returns false when the trampoline memory runs out; nothing is patched either way.
bool Hook_Prepare(uint8_t* base, const HookDef* defs, int n, const bool* use, uint8_t** tramps,
                  HookSlot* slots);

// Patches every prepared, not yet active slot with JMP detours[h] + NOP padding.
void Hook_Patch(const HookDetour* detours, HookSlot* slots, int n);

// Restores the original bytes of every active slot.
void Hook_Remove(HookSlot* slots, int n);

// Like HOOK_DETOUR, for an ENTRY hook whose handler may answer for the game function: the
// handler returns HOOK_CONTINUE (0) to run the function as usual, or HOOK_RETURN(value) to
// return to the caller at once with EAX = value and `popBytes` of stack arguments removed
// (the function's own RET N). Only for entry hooks: nothing of the function has run yet.
#define HOOK_CONTINUE 0u
#define HOOK_RETURN(value) (0x80000000u | ((uint32_t)(value) & 0x7FFFFFFFu))
#define HOOK_DETOUR_RET(name, handler, trampArray, index, popBytes)           \
    __declspec(naked) void name() {                                           \
        __asm pushad                                                          \
        __asm pushfd                                                          \
        __asm push esp                                                        \
        __asm call handler                                                    \
        __asm test eax, eax                                                   \
        __asm jnz name##_answer                                               \
        __asm popfd                                                           \
        __asm popad                                                           \
        __asm jmp dword ptr [trampArray + ((index) * 4)]                      \
    __asm name##_answer:                                                      \
        __asm and eax, 0x7FFFFFFF                                             \
        __asm mov dword ptr [esp + 0x20], eax                                 \
        __asm popfd                                                           \
        __asm popad                                                           \
        __asm ret popBytes                                                    \
    }

// Naked detour `name` for a __stdcall handler(const uint8_t* ctx); jumps through trampArray[index].
// The sequence must match the stack_calc.py header the handler reads its offsets from.
#define HOOK_DETOUR(name, handler, trampArray, index)                         \
    __declspec(naked) void name() {                                           \
        __asm pushad                                                          \
        __asm pushfd                                                          \
        __asm push esp                                                        \
        __asm call handler                                                    \
        __asm popfd                                                           \
        __asm popad                                                           \
        __asm jmp dword ptr [trampArray + ((index) * 4)]                      \
    }
