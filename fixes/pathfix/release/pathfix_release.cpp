// pathfix_release.cpp -- public release of the Shogun 2 path fix (release 1.0, from dev build v41).
//
// What it does: variant G of the path fix, always on, nothing else. When a unit's formation
// block would be laid inside a narrow stretch of its path (gate, doorway, ramp), the block is
// laid past the end of that stretch, so the men run through as a column and re-form beyond it;
// men queueing for a corner take wider lines by rank (radius lanes), aim further round the
// corner at a free point (lead the turn) and are not slowed by crowd damping there.
//
// What it does not have, compared with the dev build (fixes/pathfix/src/pathfix.cpp): no keys,
// no tones, no log, no capture, no run folders, no crash filter, no test exports, and only the
// five hooks variant G needs (the dev build installs 17). Every function below is the dev
// build's mode-G code path with the recording and the other variants' branches removed; the
// offline harness (fixes/pathfix/tests, mode "release") runs the same scenarios through the dev
// build in G and through this file and expects identical results.
//
// Safety: all five patch sites and the two game helpers it calls are byte-checked against the
// analysed Empire.Retail.dll (original 32-bit Shogun 2) before anything is written; on any
// difference nothing is installed and the game runs unmodified. At run time the hook frame,
// the corner geometry, the apex match and the radius request are checked; a failure switches
// the fix off for the rest of the session. Game memory is read through SEH-guarded copies.
//
// Addresses are Ghidra names in the analysed image (base 0x10000000), rebased at install.

